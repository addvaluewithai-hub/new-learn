// Import a learn-curriculums platform bundle (`npm run export:platform` there):
//   npm run content:import -- ../learn-curriculums/dist/platform/<course>
// Verifies every file hash and the reading package, copies each lesson under
// content/imported/<course>/<lesson>/, and regenerates the registry, module map and
// apps/platform/content-modules.json. Commit the result; `npm run content:sync`
// then writes catalog rows and releases to the database. Importing is reviewable code.
import { cp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join, resolve } from 'node:path';
import { validateReadingPackage } from '../packages/lesson-runtime/src/core.ts';
import { runtimeVersion } from '../packages/lesson-runtime/src/version.ts';

const root = resolve(new URL('..', import.meta.url).pathname);
const imported = join(root, 'content/imported');
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex');
const json = async (path) => JSON.parse(await readFile(path, 'utf8'));
const id = (value) => {
  if (!/^[a-z0-9][a-z0-9-]{1,80}$/.test(value)) throw new Error(`Unsafe identifier: ${value}`);
  return value;
};
const safePath = (path) => {
  if (!/^[\w][\w./-]*$/.test(path) || path.split('/').includes('..'))
    throw new Error(`Unsafe bundle path: ${path}`);
  return path;
};

async function verifyLesson(folder) {
  const meta = await json(join(folder, 'lesson.json'));
  for (const file of meta.files) {
    const bytes = await readFile(join(folder, safePath(file.path)));
    if (sha(bytes) !== file.sha256) throw new Error(`${meta.id}: hash mismatch in ${file.path}`);
  }
  const manifest = sha(pythonJson(meta.files));
  if (manifest !== meta.manifestHash) throw new Error(`${meta.id}: manifest hash mismatch`);
  if (meta.delivery !== 'reading') throw new Error(`${meta.id}: only reading lessons import here`);
  for (const module of Object.values(meta.renderers))
    if (!/^board\/[\w-]+\.tsx?$/.test(module)) throw new Error(`${meta.id}: bad board ${module}`);
  const pkg = await json(join(folder, 'reading.json'));
  validateReadingPackage(pkg, new Set(Object.keys(meta.renderers)));
  if (pkg.lessonId !== meta.id || pkg.contentRevision !== meta.contentRevision)
    throw new Error(`${meta.id}: package identity differs from its manifest`);
  return meta;
}

// Same bytes as Python's json.dumps(value, sort_keys=True, separators=(",", ":")).
const pythonJson = (value) =>
  JSON.stringify(sortKeys(value)).replace(
    /[\u0080-\uffff]/g,
    (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`,
  );
function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (value && typeof value === 'object')
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((key) => [key, sortKeys(value[key])]),
    );
  return value;
}

function lessonIndex(meta) {
  const boards = Object.entries(meta.renderers);
  const imports = boards.map(
    ([, module], i) => `import Board${i} from './${module.replace(/\.tsx?$/, '')}';`,
  );
  const entries = boards.map(([renderer], i) => `  ${JSON.stringify(renderer)}: Board${i},`);
  return [
    '// Generated by tools/import-content.mjs. Do not edit; re-import the bundle instead.',
    "import type { ReadingPackage, RendererRegistry } from '@learn/lesson-runtime';",
    "import lesson from './reading.json';",
    ...imports,
    '',
    'export const readingLesson = lesson as unknown as ReadingPackage;',
    'export const readingRenderers: RendererRegistry = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

async function writeRegistry() {
  const curricula = [];
  for (const course of (await readdir(imported, { withFileTypes: true })).filter((d) =>
    d.isDirectory(),
  ))
    curricula.push(await json(join(imported, course.name, 'curriculum.json')));
  curricula.sort((a, b) => a.id.localeCompare(b.id));
  await writeFile(
    join(imported, 'registry.json'),
    JSON.stringify({ schemaVersion: 1, curricula }, null, 2) + '\n',
  );
  const ready = curricula.flatMap((c) => c.lessons.filter((l) => l.moduleId));
  const loaders = ready.map(
    (l) => `  ${JSON.stringify(l.moduleId)}: () => import('./${l.curriculumId}/${l.id}/index'),`,
  );
  await writeFile(
    join(imported, 'modules.ts'),
    [
      '// Generated by tools/import-content.mjs. Allowlist of imported reading lessons.',
      'export const readingModules = {',
      ...loaders,
      '} as const;',
      '',
    ].join('\n'),
  );
  // Server side (assistant context) needs only the package JSON, never board code.
  const packages = ready.map(
    (l) =>
      `  ${JSON.stringify(l.moduleId)}: () => import('./${l.curriculumId}/${l.id}/reading.json'),`,
  );
  await writeFile(
    join(imported, 'packages.ts'),
    [
      '// Generated by tools/import-content.mjs. Reading packages for server-side context.',
      'export const readingPackages = {',
      ...packages,
      '} as const;',
      '',
    ].join('\n'),
  );
  const pinsFile = join(root, 'apps/platform/content-modules.json');
  const pins = Object.fromEntries(
    Object.entries(await json(pinsFile)).filter(([, pin]) => pin.delivery !== 'reading'),
  );
  for (const l of ready)
    pins[l.moduleId] = {
      lessonId: l.id,
      contentRevision: l.contentRevision,
      manifestHash: l.manifestHash,
      runtimeVersion: l.runtimeVersion,
      delivery: 'reading',
    };
  await writeFile(pinsFile, JSON.stringify(pins, null, 2) + '\n');
  return { curricula: curricula.length, readingLessons: ready.length };
}

const source = resolve(process.argv[2] ?? '');
const bundle = await json(join(source, 'bundle.json'));
if (bundle.kind !== 'learn-platform-bundle' || bundle.schemaVersion !== 1)
  throw new Error('Not a learn-platform-bundle v1');
const course = id(bundle.curriculumId);
const target = join(imported, course);
await rm(target, { recursive: true, force: true });
await mkdir(target, { recursive: true });
const lessons = [];
for (const entry of bundle.lessons) {
  const meta = await verifyLesson(join(source, 'lessons', id(entry.id)));
  await cp(join(source, 'lessons', meta.id), join(target, meta.id), { recursive: true });
  await writeFile(join(target, meta.id, 'index.ts'), lessonIndex(meta));
  lessons.push({
    id: meta.id,
    curriculumId: course,
    order: meta.order,
    title: meta.title,
    subtitle: meta.subtitle,
    moduleId: `reading:${meta.id}`,
    contentRevision: meta.contentRevision,
    manifestHash: meta.manifestHash,
    runtimeVersion,
    delivery: 'reading',
  });
}
for (const later of bundle.skipped ?? [])
  lessons.push({
    id: id(later.lessonId),
    curriculumId: course,
    order: later.order,
    title: later.title,
    subtitle: later.subtitle ?? '',
  });
lessons.sort((a, b) => a.order - b.order);
await writeFile(
  join(target, 'curriculum.json'),
  JSON.stringify({ id: course, ...bundle.catalog, lessons }, null, 2) + '\n',
);
console.log(
  JSON.stringify({ imported: course, lessons: lessons.length, ...(await writeRegistry()) }),
);
